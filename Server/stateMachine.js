// Статусы, с которыми можно создать новую единицу оборудования.
const EQUIPMENT_INITIAL_STATUSES = ['Работает', 'Простой', 'На консервации'];

function getNextStatuses(kind, fromStatus) {
  const map = TRANSITIONS[kind];
  if (!map) return [];
  return map[fromStatus] || [];
}

function canTransition(kind, fromStatus, toStatus) {
  if (fromStatus === toStatus) return true;
  return getNextStatuses(kind, fromStatus).includes(toStatus);
}

